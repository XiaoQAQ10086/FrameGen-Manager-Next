const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const read = (name) => {
  const value = JSON.parse(fs.readFileSync(path.join(root, 'l10n', name), 'utf8'));
  return Object.fromEntries(
    Object.entries(value).filter(([key, text]) => !key.startsWith('@') && typeof text === 'string'),
  );
};

const zh = read('app_zh.arb');
const en = read('app_en.arb');
const output = `// Generated by scripts/generate-l10n.js from l10n/*.arb — do not edit.
const ZH = ${JSON.stringify(zh, null, 2)};
const EN = ${JSON.stringify(en, null, 2)};

let current = 'zh';

export function setLanguage(language) {
  const value = String(language || 'system').toLowerCase();
  if (value === 'en' || value === 'english') current = 'en';
  else if (value === 'zh' || value === 'chinesesimplified') current = 'zh';
  else current = (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function language() {
  return current;
}

export function t(key, params = {}) {
  const table = current === 'en' ? EN : ZH;
  let text = table[key] ?? ZH[key] ?? key;
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(\`{\${name}}\`, String(value));
  }
  return text;
}
`;
fs.writeFileSync(path.join(root, 'renderer', 'l10n.js'), output);
console.log(`l10n: ${Object.keys(zh).length} keys`);
