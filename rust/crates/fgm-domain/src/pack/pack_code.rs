/// Stable pack validation codes shared by the CLI, logs and UI error mapping.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum PackCode {
    SchemaVersion,
    InvalidId,
    InvalidVersion,
    DisplayName,
    MinAppVersion,
    GpuRoutes,
    Files,
    Path,
    DuplicateTarget,
    Role,
    ProxySlot,
    Sha256,
    Size,
    IniMode,
    StockValue,
    StepType,
    StepArguments,
    InstallerTrust,
    IniTargetConflict,
    MinAppTooNew,
    DuplicateStockValue,
    NullEntry,
    DuplicateGpuRoute,
    IniTemplateSha256,
    IniTemplateSize,
    DuplicateOwnedDirectory,
    OwnedDirectoryConflict,
    PayloadMissing,
    PayloadSize,
    PayloadHash,
    IniTemplateMissing,
    PayloadIo,
    IniTemplateMismatch,
    InstallerPayload,
}

impl PackCode {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::SchemaVersion => "PACK-001",
            Self::InvalidId => "PACK-002",
            Self::InvalidVersion => "PACK-003",
            Self::DisplayName => "PACK-004",
            Self::MinAppVersion => "PACK-005",
            Self::GpuRoutes => "PACK-006",
            Self::Files => "PACK-007",
            Self::Path => "PACK-008",
            Self::DuplicateTarget => "PACK-009",
            Self::Role => "PACK-010",
            Self::ProxySlot => "PACK-011",
            Self::Sha256 => "PACK-012",
            Self::Size => "PACK-013",
            Self::IniMode => "PACK-014",
            Self::StockValue => "PACK-015",
            Self::StepType => "PACK-016",
            Self::StepArguments => "PACK-017",
            Self::InstallerTrust => "PACK-018",
            Self::IniTargetConflict => "PACK-019",
            Self::MinAppTooNew => "PACK-020",
            Self::DuplicateStockValue => "PACK-021",
            Self::NullEntry => "PACK-022",
            Self::DuplicateGpuRoute => "PACK-023",
            Self::IniTemplateSha256 => "PACK-024",
            Self::IniTemplateSize => "PACK-025",
            Self::DuplicateOwnedDirectory => "PACK-026",
            Self::OwnedDirectoryConflict => "PACK-027",
            Self::PayloadMissing => "PACK-101",
            Self::PayloadSize => "PACK-102",
            Self::PayloadHash => "PACK-103",
            Self::IniTemplateMissing => "PACK-104",
            Self::PayloadIo => "PACK-105",
            Self::IniTemplateMismatch => "PACK-106",
            Self::InstallerPayload => "PACK-107",
        }
    }
}
